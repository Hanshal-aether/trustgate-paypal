"""
ML scoring for TrustGate.

Loads the model produced by `python training/train.py`:
    app/model/trustgate_lgb.txt    <- LightGBM model, portable text format
    app/model/model_meta.json      <- feature list, email-domain frequencies, calibration curve, thresholds

If those files are missing (or lightgbm isn't installed) ML is simply DISABLED and the rule engine keeps working on
its own. Nothing crashes: a fraud layer must never take signup down.

Honesty note: the model is trained on SYNTHETIC signup data generated by training/generate_synthetic.py. It learns
our assumptions about abuse patterns, not real-world ones. Treat it as a second opinion next to the rules.
"""
import json
import os
from pathlib import Path
from typing import Optional

import numpy as np

from app.features import email_features
from app.redis_client import identity_history

MODEL_DIR = Path(os.getenv("TRUSTGATE_MODEL_DIR", Path(__file__).parent / "model"))

_booster = None
_meta: Optional[dict] = None


def _load() -> bool:
    global _booster, _meta
    model_path, meta_path = MODEL_DIR / "trustgate_lgb.txt", MODEL_DIR / "model_meta.json"
    if not (model_path.exists() and meta_path.exists()):
        return False
    try:
        import lightgbm as lgb
        _booster = lgb.Booster(model_file=str(model_path))
        _meta = json.loads(meta_path.read_text())
        return True
    except Exception:           # missing lib, corrupt file, version problem -> stay disabled
        _booster, _meta = None, None
        return False


ML_AVAILABLE = _load()


def status() -> dict:
    return {
        "ml_enabled": ML_AVAILABLE,
        "features": _meta["features"] if _meta else None,
        "thresholds": _meta["thresholds"] if _meta else None,
        "trained_on": _meta.get("trained_on") if _meta else None,
        "valid_metrics": _meta.get("valid_metrics") if _meta else None,
    }


def calibrate(p_raw: float) -> float:
    cal = _meta["calibration"]
    return float(np.interp(p_raw, cal["x"], cal["y"]))


def to_risk_score(p: float, flag_t: float, block_t: float) -> float:
    """Map a calibrated probability onto the same 0-100 scale as the rule engine:
    flag threshold -> 40, block threshold -> 70, saturating at 100."""
    if p < flag_t:
        return 40.0 * p / max(flag_t, 1e-9)
    if p < block_t:
        return 40.0 + 30.0 * (p - flag_t) / max(block_t - flag_t, 1e-9)
    return min(100.0, 70.0 + 30.0 * (p - block_t) / max(block_t, 1e-9))


def _device_type(user_agent: Optional[str]) -> float:
    if not user_agent:
        return float("nan")
    try:
        from user_agents import parse
        ua = parse(user_agent)
        if ua.is_mobile or ua.is_tablet:
            return 1.0
        if ua.is_pc:
            return 0.0
    except Exception:
        pass
    return float("nan")


def build_features(email: str, fingerprint: str, user_agent: Optional[str], now: Optional[float], record: bool) -> dict:
    hist = identity_history(f"id:{fingerprint}", now=now, record=record)
    feats = email_features(email, _meta["email_domain_freq"])
    feats.update({
        "device_type": _device_type(user_agent),
        "idn_n_prev": float(hist["n_prev"]),
        "idn_secs_since_prev": float(hist["secs_since_prev"]),
        "idn_same_hour": float(hist["same_hour"]),
        "idn_same_day": float(hist["same_day"]),
    })
    return feats


def score_event(email: str, fingerprint: str, user_agent: Optional[str] = None,
                now: Optional[float] = None, record: bool = True) -> Optional[dict]:
    """Returns None when ML is disabled. Otherwise: risk_score (0-100), probability, reasons, features."""
    if not ML_AVAILABLE:
        return None
    feats = build_features(email, fingerprint, user_agent, now, record)
    names = _meta["features"]
    row = np.array([[feats[n] for n in names]], dtype="float64")
    p_raw = float(_booster.predict(row)[0])
    p = calibrate(p_raw)
    thr = _meta["thresholds"]
    risk = round(to_risk_score(p, thr["flag"], thr["block"]), 1)

    # per-prediction explanation straight from LightGBM (no extra library): positive contributions push risk up
    contrib = _booster.predict(row, pred_contrib=True)[0][:-1]
    order = np.argsort(-contrib)[:3]
    texts = _meta.get("reason_text", {})
    reasons = [f"ml: {texts.get(names[i], names[i])}" for i in order if contrib[i] > 0.05] if risk >= 40 else []   # explain only flags/blocks

    return {"risk_score": risk, "probability": round(p, 4), "reasons": reasons, "features": feats}
